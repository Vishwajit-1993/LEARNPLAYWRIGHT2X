//Arithmatic Operators
//used to perform arithmetic operations on variables (left side of the operator)
let a = 10;
let b = 20;
console.log(a + b); //30
console.log(a - b); //-10
console.log(a * b); //200
console.log(a / b); //0.5
console.log(a % b); //10
console.log(a ** b); //10^20
console.log(a++); //10
console.log(a--); //10
console.log(++a); //11
console.log(--a); //10
