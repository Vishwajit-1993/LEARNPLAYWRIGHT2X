//Literal is a value that is given to a variable, function, class, etc.

let a = 10; //10 is a numeric literal assigned to variable a
let b = "Hello"; //"Hello" is a string literal assigned to variable b
let c = true; //true is a boolean literal assigned to variable c
let d = false; //false is a boolean literal assigned to variable d
let e = null; //null is a null literal assigned to variable e
let f = undefined; //undefined is a undefined literal assigned to variable f
let g = Symbol("Hello"); //Symbol("Hello") is a symbol literal assigned to variable g
let h = [1, 2, 3]; //[1, 2, 3] is an array literal assigned to variable h
let i = { name: "John", age: 20 }; //{name: "John", age: 20} is an object literal assigned to variable i
let j = function () {
  console.log("Hello");
}; //function() {console.log("Hello");} is a function literal assigned to variable j

console.log(typeof a);
console.log(typeof b);
console.log(typeof c);
console.log(typeof d);
console.log(typeof e);
console.log(typeof f);
console.log(typeof g);
console.log(typeof h);
console.log(typeof i);
console.log(typeof j);
