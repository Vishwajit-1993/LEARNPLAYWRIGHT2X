//switch statement is used to perform different actions based on different conditions.

let day = 10;

switch (day) {
  case 1:
    console.log("Monday");

  case 2:
    console.log("Tuesday");

  case 3:
    console.log("Wednesday");

  case 4:
    console.log("Thursday");

  case 5:
    console.log("Friday");

  case 6:
    console.log("Saturday");

  case 7:
    console.log("Sunday");

  default:
    console.log("Invalid day");
}

//if we don't use break statement, the code will continue to execute the next case. Based on the condition, an the input of the user, the code will execute the next case.
