let browser = "Safari";

switch (browser) {
  case "Chrome":
  case "Edge":
  case "Brave":
  case "Opera":
    console.log("You are using chrome based browser");
    break;
  case "Firefox":
    console.log("You are using Firefox based browser");
    break;
  case "Safari":
    console.log("You are using Safari based browser");
    break;
  default:
    console.log("You are using a different browser");
}
