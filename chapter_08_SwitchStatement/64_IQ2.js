let test_score = 65;

switch (true) {
  case test_score >= 90:
    console.log("You got A grade");
    break;
  case test_score >= 80:
    console.log("You got B grade");
    break;
  case test_score >= 70:
    console.log("You got C grade");
    break;
  default:
    console.log("You are failed");
    break;
}
