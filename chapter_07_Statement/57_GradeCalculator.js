let marks = 89;

if (marks >= 90) {
  console.log("You got A grade");
} else if (marks >= 80) {
  console.log("You got B grade");
} else if (marks <= 79 && marks >= 70) {
  console.log("You got C grade");
} else if (marks <= 69 && marks >= 60) {
  console.log("You got D grade");
} else {
  console.log("You are failed");
}
